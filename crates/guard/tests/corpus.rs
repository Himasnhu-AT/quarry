fn outcome(sql: &str, engine: EngineKind) -> Want {
    match classify(sql, engine, &Policy::default()) {
        Verdict::Read(_) => Read,
        Verdict::Write(_) => Write,
        Verdict::Refused(r) => No(r.code),
    }
}

#[test]
fn corpus_has_at_least_200_cases_per_dialect() {
    let pg = CORPUS.iter().filter(|(on, ..)| matches!(on, Both | Pg)).count();
    let lite = CORPUS.iter().filter(|(on, ..)| matches!(on, Both | Lite)).count();
    assert!(pg >= 200 && lite >= 200, "pg {pg}, sqlite {lite}");
}

#[test]
fn corpus() {
    let mut bad = Vec::new();
    for (on, sql, want) in CORPUS {
        let engines: &[EngineKind] = match on {
            Both => &[EngineKind::Postgres, EngineKind::Sqlite],
            Pg => &[EngineKind::Postgres],
            Lite => &[EngineKind::Sqlite],
        };
        for &engine in engines {
            let got = outcome(sql, engine);
            if got != *want {
                let msg = match classify(sql, engine, &Policy::default()) {
                    Verdict::Refused(r) => r.to_string(),
                    _ => String::new(),
                };
                bad.push(format!("{engine:?} {sql:?}: want {want:?}, got {got:?} {msg}"));
            }
        }
    }
    assert!(bad.is_empty(), "{} mismatches:\n{}", bad.len(), bad.join("\n"));
}

#[test]
fn every_read_runs_as_its_canonical_text() {
    for (on, sql, want) in CORPUS {
        if *want != Read {
            continue;
        }
        let engines: &[EngineKind] = match on {
            Both => &[EngineKind::Postgres, EngineKind::Sqlite],
            Pg => &[EngineKind::Postgres],
            Lite => &[EngineKind::Sqlite],
        };
        for &engine in engines {
            let Verdict::Read(r) = classify(sql, engine, &Policy::default()) else { continue };
            let dialect: Box<dyn Dialect> = match engine {
                EngineKind::Postgres => Box::new(PostgreSqlDialect {}),
                EngineKind::Sqlite => Box::new(SQLiteDialect {}),
            };
            let toks = Tokenizer::new(&*dialect, r.sql()).tokenize().unwrap();
            assert!(
                !toks.iter().any(|t| matches!(t, Token::Whitespace(Whitespace::SingleLineComment { .. } | Whitespace::MultiLineComment(_)))),
                "{sql}: comments survive in {}",
                r.sql()
            );
            // Classifying the canonical text again gives the same statement.
            match classify(r.sql(), engine, &Policy::default()) {
                Verdict::Read(again) => assert_eq!(again.sql(), r.sql(), "{sql}"),
                other => panic!("{sql}: canonical {} is now {other:?}", r.sql()),
            }
        }
    }
}
